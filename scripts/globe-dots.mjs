// Generates src/components/network/globeDots.ts: which points of a Fibonacci sphere
// fall on land, and which of those are in India.
//
// The map data is only needed to regenerate the file, so it is not a dependency:
//   npm i --no-save world-atlas@2 topojson-client@3 d3-geo@3 && node scripts/globe-dots.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { geoContains } from "d3-geo";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const world = JSON.parse(readFileSync(require.resolve("world-atlas/countries-50m.json"), "utf8"));
const land = feature(world, world.objects.land);
const countries = feature(world, world.objects.countries).features;
const highlighted = countries.filter((c) => c.id === "356"); // India

const COUNT = 60000;
const GOLDEN = Math.PI * (3 - Math.sqrt(5));

// Must match fibonacciPoint() in globeDots.ts.
function point(i) {
  const y = 1 - ((i + 0.5) * 2) / COUNT;
  const theta = GOLDEN * i;
  const lat = (Math.asin(y) * 180) / Math.PI;
  const lon = ((((theta % (2 * Math.PI)) + 2 * Math.PI) % (2 * Math.PI)) * 180) / Math.PI - 180;
  return [lon, lat];
}

const landBits = new Uint8Array(Math.ceil(COUNT / 8));
const markBits = new Uint8Array(Math.ceil(COUNT / 8));
let onLand = 0;
let marked = 0;
for (let i = 0; i < COUNT; i++) {
  const p = point(i);
  if (!geoContains(land, p)) continue;
  landBits[i >> 3] |= 1 << (i & 7);
  onLand++;
  if (highlighted.some((c) => geoContains(c, p))) {
    markBits[i >> 3] |= 1 << (i & 7);
    marked++;
  }
}

const b64 = (bytes) => Buffer.from(bytes).toString("base64");
const out = `// Generated by scripts/globe-dots.mjs from Natural Earth 1:50m (world-atlas). Do not edit.
// ${onLand} of ${COUNT} sphere points are on land; ${marked} of them are in India.

export const DOT_COUNT = ${COUNT};
export const LAND_BITS = "${b64(landBits)}";
export const MARK_BITS = "${b64(markBits)}";

const GOLDEN = Math.PI * (3 - Math.sqrt(5));

/** Longitude and latitude in degrees of point i of the sphere; must match the generator. */
export function fibonacciPoint(i: number): [lon: number, lat: number] {
  const y = 1 - ((i + 0.5) * 2) / DOT_COUNT;
  const theta = GOLDEN * i;
  const lat = (Math.asin(y) * 180) / Math.PI;
  const lon = ((((theta % (2 * Math.PI)) + 2 * Math.PI) % (2 * Math.PI)) * 180) / Math.PI - 180;
  return [lon, lat];
}
`;
writeFileSync(new URL("../src/components/network/globeDots.ts", import.meta.url), out);
console.log({ onLand, marked, bytes: out.length });
